//! Pre-outcome baselines for ordinary and selected adaptive contraction.
//!
//! The degree-three hub has sites `w` and `k`, and three leaves carry `x_j`.
//! `w = k.prime()` deliberately distinguishes full index identity from ID.
//! The two right patches fix `k`: their contributions are `3 F` and `-2 F`,
//! where `F(w, x) = (w + 1) (2 |000> + 4 |111>)`. Each contribution has
//! exact bond rank two. A cap of two therefore forces the Sequential shortcut
//! to split, even though the contribution sum has the same exact rank.
//! Values and projectors below are analytical expectations, not a snapshot
//! generated by the implementation under test.

use num_complex::Complex64;
use tensor4all_core::{DynIndex, IdxTensor, TensorElement};
use tensor4all_partitionedtreetn::{
    contract_adaptive, contract_adaptive_selected, BudgetAllocation, PartitionedTreeTN,
    PartitionedTreeTNError, PatchSplitStrategy, PatchingOptions, Projector, SubDomainTreeTN,
};
use tensor4all_treetn::{contraction::ContractionOptions, SumEngine, TreeTN};

struct Fixture {
    left: PartitionedTreeTN,
    right: PartitionedTreeTN,
    output_sites: Vec<DynIndex>,
}

impl Fixture {
    fn new<T: TensorElement + From<f64>>(left_value: impl Fn(f64) -> T) -> Self {
        let contracted = DynIndex::new_dyn(2);
        let spectator = contracted.prime();
        assert_ne!(spectator, contracted);
        let leaves: Vec<_> = (0..3).map(|_| DynIndex::new_dyn(2)).collect();
        let bonds: Vec<_> = (0..3).map(|_| DynIndex::new_dyn(2)).collect();
        // Column-major (w, k, b0, b1, b2): only b0 = b1 = b2 contributes.
        let mut values = vec![T::from(0.0); 32];
        for w in 0..2 {
            for k in 0..2 {
                for channel in 0..2 {
                    values[w + 2 * k + 28 * channel] =
                        left_value((w + 1) as f64 * (k + 1) as f64 * (2 * (channel + 1)) as f64);
                }
            }
        }
        let mut hub_indices = vec![spectator.clone(), contracted.clone()];
        hub_indices.extend(bonds.iter().cloned());
        let mut tensors = vec![IdxTensor::from_dense(hub_indices, values).unwrap()];
        for (bond, site) in bonds.into_iter().zip(&leaves) {
            tensors.push(
                IdxTensor::from_dense(
                    vec![bond, site.clone()],
                    [1.0, 0.0, 0.0, 1.0].map(T::from).to_vec(),
                )
                .unwrap(),
            );
        }
        let left_tree = TreeTN::from_tensors(tensors, vec![0, 1, 2, 3]).unwrap();
        let left = PartitionedTreeTN::from_subdomains(
            (0..2)
                .map(|w| {
                    SubDomainTreeTN::new(
                        left_tree.clone(),
                        Projector::from_pairs([(spectator.clone(), w)]).unwrap(),
                    )
                    .unwrap()
                })
                .collect(),
        )
        .unwrap();

        let bonds: Vec<_> = (0..3).map(|_| DynIndex::new_dyn(1)).collect();
        let mut hub_indices = vec![contracted.clone()];
        hub_indices.extend(bonds.iter().cloned());
        let mut tensors =
            vec![IdxTensor::from_dense(hub_indices, [3.0, -1.0].map(T::from).to_vec()).unwrap()];
        tensors.extend(
            bonds
                .into_iter()
                .map(|bond| IdxTensor::from_dense(vec![bond], vec![T::from(1.0)]).unwrap()),
        );
        let right_tree = TreeTN::from_tensors(tensors, vec![0, 1, 2, 3]).unwrap();
        let right = PartitionedTreeTN::from_subdomains(
            (0..2)
                .map(|k| {
                    SubDomainTreeTN::new(
                        right_tree.clone(),
                        Projector::from_pairs([(contracted.clone(), k)]).unwrap(),
                    )
                    .unwrap()
                })
                .collect(),
        )
        .unwrap();
        let mut output_sites = vec![spectator];
        output_sites.extend(leaves);
        Self {
            left,
            right,
            output_sites,
        }
    }

    fn options(
        &self,
        strategy: PatchSplitStrategy,
        engine: SumEngine,
        cap: Option<usize>,
        split: bool,
    ) -> PatchingOptions {
        PatchingOptions {
            cutoff: 1e-24,
            allocation: BudgetAllocation::Volume,
            max_bond_dim: cap,
            // Every input group already fixes w. Choosing it leaves no split
            // candidate, so the blocked case must return the full group sum.
            patch_order: vec![self.output_sites[usize::from(split)].clone()],
            split_strategy: strategy,
            sum_engine: engine,
        }
    }

    fn assert_result<T: TensorElement + From<f64>>(
        &self,
        result: &PartitionedTreeTN,
        kept_w: &[usize],
        split: bool,
        value: impl Fn(f64) -> T,
    ) {
        assert_eq!(result.len(), kept_w.len() * if split { 2 } else { 1 });
        for &w in kept_w {
            for x in 0..if split { 2 } else { 1 } {
                let mut fixed = vec![(self.output_sites[0].clone(), w)];
                if split {
                    fixed.push((self.output_sites[1].clone(), x));
                }
                let projector = Projector::from_pairs(fixed).unwrap();
                let patch = result.get(&projector).expect("baseline projector");
                assert_eq!(patch.node_count(), 4);
                assert_eq!(patch.max_bond_dim(), if split { 1 } else { 2 });
            }
        }
        // Column-major (w, x0, x1, x2): nonzero only on the two GHZ corners.
        let mut expected = vec![T::from(0.0); 16];
        for &w in kept_w {
            expected[w] = value(2.0 * (w + 1) as f64);
            expected[w + 14] = value(4.0 * (w + 1) as f64);
        }
        let expected = IdxTensor::from_dense(self.output_sites.clone(), expected).unwrap();
        let actual = result.to_treetn().unwrap().to_dense().unwrap();
        let residual = actual.sub(&expected).unwrap().maxabs().unwrap();
        assert!(
            residual < 1e-10,
            "baseline max-absolute residual: {residual:e}"
        );
    }
}

fn baseline<T: TensorElement + From<f64>>(value: impl Fn(f64) -> T + Copy) {
    let fixture = Fixture::new(value);
    for strategy in [
        PatchSplitStrategy::Sequential,
        PatchSplitStrategy::ExactParameterGain,
    ] {
        for engine in [SumEngine::Binary, SumEngine::Nary] {
            // Equality with the cap splits; a larger cap and an absent cap
            // retain the rank-two parent, as does an exhausted patch order.
            for (cap, can_split, expected_split) in [
                (Some(2), true, true),
                (Some(3), true, false),
                (None, true, false),
                (Some(2), false, false),
            ] {
                let options = fixture.options(strategy, engine, cap, can_split);
                let ordinary = contract_adaptive(
                    &fixture.left,
                    &fixture.right,
                    &0,
                    &ContractionOptions::zipup(),
                    &options,
                )
                .unwrap();
                fixture.assert_result(&ordinary, &[0, 1], expected_split, value);
                let wanted = Projector::from_pairs([(fixture.output_sites[0].clone(), 1)]).unwrap();
                let selected = contract_adaptive_selected(
                    &fixture.left,
                    &fixture.right,
                    &0,
                    &ContractionOptions::zipup(),
                    &options,
                    &[wanted.clone(), wanted],
                )
                .unwrap();
                fixture.assert_result(&selected, &[1], expected_split, value);
            }
        }
    }
}

#[test]
fn ordinary_and_selected_branched_real_baselines() {
    baseline::<f64>(|x| x);
}

#[test]
fn ordinary_and_selected_branched_complex_baselines() {
    baseline::<Complex64>(|x| Complex64::new(x, x));
}

#[test]
fn selection_matches_top_level_groups_and_validation_precedes_empty_selection() {
    let fixture = Fixture::new::<f64>(|x| x);
    let options = fixture.options(
        PatchSplitStrategy::Sequential,
        SumEngine::Binary,
        Some(2),
        true,
    );
    // A descendant projector is not a request to select its ancestor group.
    let descendant = Projector::from_pairs([
        (fixture.output_sites[0].clone(), 1),
        (fixture.output_sites[1].clone(), 0),
    ])
    .unwrap();
    for wanted in [vec![], vec![descendant]] {
        let result = contract_adaptive_selected(
            &fixture.left,
            &fixture.right,
            &0,
            &ContractionOptions::zipup(),
            &options,
            &wanted,
        )
        .unwrap();
        assert!(result.is_empty());
        let invalid = ContractionOptions::zipup().with_max_bond_dim(0);
        let error = contract_adaptive_selected(
            &fixture.left,
            &fixture.right,
            &0,
            &invalid,
            &options,
            &wanted,
        )
        .unwrap_err();
        assert!(matches!(
            error,
            PartitionedTreeTNError::InvalidOptions { .. }
        ));
    }
}
